-- ==========================================================
-- VIOTRACK SUPABASE DATABASE SCHEMA & STARTER SEED DATA
-- Run this in your Supabase SQL Editor (supabase.com/dashboard)
-- ==========================================================

-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Drop existing tables if re-initializing (Order matters for Foreign Keys)
DROP TABLE IF EXISTS sms_logs CASCADE;
DROP TABLE IF EXISTS meetings CASCADE;
DROP TABLE IF EXISTS activity_logs CASCADE;
DROP TABLE IF EXISTS records CASCADE;
DROP TABLE IF EXISTS advisers CASCADE;
DROP TABLE IF EXISTS violations CASCADE;
DROP TABLE IF EXISTS teachers CASCADE;
DROP TABLE IF EXISTS admins CASCADE;
DROP TABLE IF EXISTS students CASCADE;

-- ==========================================================
-- 3. CREATE TABLES
-- ==========================================================

-- STUDENTS TABLE
CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lrn VARCHAR(50) UNIQUE NOT NULL,
    fname VARCHAR(100) NOT NULL,
    mname VARCHAR(100) DEFAULT '',
    lname VARCHAR(100) NOT NULL,
    grade VARCHAR(20) NOT NULL,
    section VARCHAR(50) NOT NULL,
    academicyear VARCHAR(20) DEFAULT '2025-2026',
    gender VARCHAR(10) DEFAULT 'Male',
    contact VARCHAR(30) DEFAULT '',
    parent_name VARCHAR(150) DEFAULT '',
    parent_contact VARCHAR(30) DEFAULT '',
    address TEXT DEFAULT '',
    image TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ADMINS TABLE
CREATE TABLE admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fname VARCHAR(100) NOT NULL,
    lname VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'admin',
    image TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- TEACHERS TABLE
CREATE TABLE teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fname VARCHAR(100) NOT NULL,
    lname VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    position VARCHAR(100) DEFAULT 'Teacher I',
    department VARCHAR(100) DEFAULT 'Junior High School',
    contact VARCHAR(30) DEFAULT '',
    image TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ADVISERS (Teacher Section Assignments)
CREATE TABLE advisers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT REFERENCES teachers(id) ON DELETE CASCADE,
    grade_level VARCHAR(20) NOT NULL,
    class_section VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(grade_level, class_section)
);

-- VIOLATION CATEGORIES & TYPES
CREATE TABLE violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    type VARCHAR(30) NOT NULL CHECK (type IN ('Minor', 'Major')),
    default_sanction TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- VIOLATION RECORDS (Incident Logs)
CREATE TABLE records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(id) ON DELETE CASCADE,
    violation_id BIGINT REFERENCES violations(id) ON DELETE SET NULL,
    reported_by_id BIGINT,
    reported_by_type VARCHAR(20) DEFAULT 'admin', -- 'admin' or 'teacher'
    reported_by_name VARCHAR(150),
    date_reported TIMESTAMPTZ DEFAULT NOW(),
    status VARCHAR(30) DEFAULT 'Pending' CHECK (status IN ('Pending', 'Investigation', 'Resolved', 'Dismissed', 'Under Approval', 'Rejected')),
    approval_status VARCHAR(30) DEFAULT 'Approved' CHECK (approval_status IN ('Under Approval', 'Approved', 'Rejected')),
    approved_by VARCHAR(150),
    approved_at TIMESTAMPTZ,
    rejected_by VARCHAR(150),
    rejected_at TIMESTAMPTZ,
    rejection_reason TEXT,
    sanction TEXT DEFAULT '',
    remarks TEXT DEFAULT '',
    resolution_notes TEXT DEFAULT '',
    resolution_date TIMESTAMPTZ,
    sms_notified BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ACTIVITY / AUDIT LOGS
CREATE TABLE activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(150) NOT NULL,
    user_role VARCHAR(50) NOT NULL,
    action VARCHAR(100) NOT NULL,
    details TEXT,
    ip_address VARCHAR(50) DEFAULT '127.0.0.1',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- PARENT-TEACHER MEETINGS
CREATE TABLE meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT REFERENCES records(id) ON DELETE CASCADE,
    student_id BIGINT REFERENCES students(id) ON DELETE CASCADE,
    parent_name VARCHAR(150) NOT NULL,
    meeting_date DATE NOT NULL,
    meeting_time TIME NOT NULL,
    status VARCHAR(30) DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'Completed', 'Cancelled', 'No Show')),
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- SMS NOTIFICATION LOGS
CREATE TABLE sms_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(id) ON DELETE CASCADE,
    record_id BIGINT REFERENCES records(id) ON DELETE SET NULL,
    recipient_name VARCHAR(150),
    phone_number VARCHAR(30) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(20) DEFAULT 'Sent',
    sent_at TIMESTAMPTZ DEFAULT NOW()
);

